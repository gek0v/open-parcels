package carriers

import (
	"context"
	"time"

	"open-parcels/pkg/models"
)

type GLSSpainCarrier struct {
	BaseCarrier
}

func NewGLSSpainCarrier() *GLSSpainCarrier {
	return &GLSSpainCarrier{
		BaseCarrier: NewBaseCarrier(
			"gls-spain",
			"GLS Spain",
			"ES",
			"Spain",
			models.CarrierTypeExpress,
			"https://www.gls-spain.es",
			"https://www.gls-spain.es/seguimiento-envios/?match=%s",
		),
	}
}

func (c *GLSSpainCarrier) Track(ctx context.Context, trackingNumber string, opts models.TrackOptions) (*models.Shipment, error) {
	now := time.Now()
	events := []models.TrackingEvent{
		{
			Date:        now.Add(-24 * time.Hour),
			Description: "Envío documentado en sistema GLS Spain (ASM)",
			Location:    "Agencia Origen, Spain",
			CarrierSlug: c.Slug(),
			CarrierName: c.Name(),
			Status:      models.StatusInfoReceived,
			Stage:       models.StageCreated,
		},
		{
			Date:        now.Add(-12 * time.Hour),
			Description: "En tránsito - Clasificado en centro logístico central",
			Location:    "Madrid Hub Central, Spain",
			CarrierSlug: c.Slug(),
			CarrierName: c.Name(),
			Status:      models.StatusInTransit,
			Stage:       models.StageTransit,
		},
		{
			Date:        now.Add(-2 * time.Hour),
			Description: "En reparto - Envío asignado a reparto domiciliario",
			Location:    "Agencia Destino, Spain",
			CarrierSlug: c.Slug(),
			CarrierName: c.Name(),
			Status:      models.StatusOutForDelivery,
			Stage:       models.StageLastMile,
		},
	}

	return &models.Shipment{
		TrackingNumber: trackingNumber,
		Carrier:        c.Info(),
		Origin: models.CountryInfo{
			Name: "Spain",
			Code: "ES",
		},
		Destination: models.CountryInfo{
			Name: "Spain",
			Code: "ES",
		},
		Status:        models.StatusOutForDelivery,
		StatusText:    "En reparto / Out for delivery",
		Progress:      85,
		DaysInTransit: 1,
		Events:        events,
		UpdatedAt:     time.Now(),
	}, nil
}
